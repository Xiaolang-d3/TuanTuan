"""Upgrade real older workspaces (SQL dumps produced by those releases' init_db).

The fixtures were generated by running ``init_db`` from origin/main (v27) and
from the protocol-negotiation branch (v28), plus one model event and one
conversation, so these tests exercise the real old schemas instead of a
current database with columns dropped. The v29 snapshots cover both the
chat-assets (b720d98) and LiteLLM (f2a3fba) branch schemas with synthetic data.
"""
from __future__ import annotations

import sqlite3
from pathlib import Path

import pytest

from app.db import DB_SCHEMA_VERSION, init_db
from app.persistence.upgrades import migration_name

FIXTURES = Path(__file__).parent / "fixtures"


def load(version: int | str, tmp_path: Path) -> Path:
    path = tmp_path / "tuantuan.db"
    with sqlite3.connect(path) as conn:
        conn.executescript((FIXTURES / f"workspace_v{version}.sql").read_text(encoding="utf-8"))
    return path


def columns(conn: sqlite3.Connection, table: str) -> set[str]:
    return {row[1] for row in conn.execute(f"PRAGMA table_info({table})")}


@pytest.mark.parametrize("version", [27, 28, "29_chat", "29_litellm"])
def test_real_old_workspace_upgrades_to_current(tmp_path, version):
    path = load(version, tmp_path)
    old_version = 29 if isinstance(version, str) else version
    with sqlite3.connect(path) as conn:
        assert conn.execute("SELECT MAX(version) FROM schema_migrations").fetchone()[0] == old_version
        before_tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        before_counts = {table: conn.execute(f'SELECT COUNT(*) FROM "{table}"').fetchone()[0] for table in before_tables}

    init_db(path)

    with sqlite3.connect(path) as conn:
        assert conn.execute("PRAGMA integrity_check").fetchone()[0] == "ok"
        assert conn.execute("PRAGMA foreign_key_check").fetchall() == []
        migrations = dict(conn.execute("SELECT version, name FROM schema_migrations"))
        assert migrations[old_version] == ("litellm_model_layer" if version == "29_litellm" else "independent_library")
        assert migrations[DB_SCHEMA_VERSION] == migration_name(DB_SCHEMA_VERSION) == "workspace_projects"
        # No existing row is lost (schema_migrations gains one row).
        for table, count in before_counts.items():
            expected = count + 1 if table == "schema_migrations" else count
            assert conn.execute(f'SELECT COUNT(*) FROM "{table}"').fetchone()[0] == expected, table
        assert conn.execute("SELECT title FROM conversations WHERE title = 'fixture-conversation'").fetchone()
        event = conn.execute("SELECT model_name, cost_usd, backend, fallback_from_profile_id FROM model_service_events").fetchone()
        assert event == ("gpt-4o", None, "", "")
        assert {"detected_protocol", "deleted_at"} <= columns(conn, "model_connections")
        assert {"reasoning_effort"} <= columns(conn, "model_profiles")
        assert {"cost_usd", "backend", "fallback_from_profile_id"} <= columns(conn, "model_service_events")
        tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        assert {"model_fallback_policy", "model_capability_records", "chat_image_assets", "chat_image_operations"} <= tables
        assert {"library_collections", "library_collection_sources"} <= tables
        assert {"conversation_context_seeds", "image_studio_tasks", "image_studio_works"} <= tables
        assert {"projects", "project_items"} <= tables
        assert conn.execute("SELECT COUNT(*) FROM projects").fetchone()[0] == 0
        assert conn.execute("SELECT COUNT(*) FROM project_items").fetchone()[0] == 0
        assert {"model_selection_json"} <= columns(conn, "agent_execution_runs")

    backup = tmp_path / ".upgrade-backups" / f"before-schema-v{DB_SCHEMA_VERSION}" / "tuantuan.db"
    with sqlite3.connect(backup) as conn:
        assert conn.execute("SELECT MAX(version) FROM schema_migrations").fetchone()[0] == old_version

    init_db(path)  # idempotent
    with sqlite3.connect(path) as conn:
        assert conn.execute("SELECT COUNT(*) FROM schema_migrations WHERE version = ?", (DB_SCHEMA_VERSION,)).fetchone()[0] == 1


def test_fresh_workspace_records_named_current_migration(tmp_path):
    path = tmp_path / "tuantuan.db"
    init_db(path)
    with sqlite3.connect(path) as conn:
        assert conn.execute("SELECT version, name FROM schema_migrations").fetchall() == [
            (DB_SCHEMA_VERSION, "workspace_projects"),
        ]


def test_v48_projects_upgrade_preserves_v47_marker_and_legacy_sources(tmp_path):
    path = tmp_path / "tuantuan.db"
    init_db(path)
    with sqlite3.connect(path) as conn:
        # Simulate the pre-project schema; #128 owns the actual v47 migration.
        conn.execute("DROP TABLE project_items")
        conn.execute("DROP TABLE projects")
        conn.execute("UPDATE schema_migrations SET version=47, name='reserved_for_128'")
        conn.execute("INSERT INTO library_sources(title, content_hash, content) VALUES ('旧资料', 'old', 'legacy body')")
        before_sources = conn.execute("SELECT * FROM library_sources").fetchall()
        before_chats = conn.execute("SELECT * FROM conversations").fetchall()

    init_db(path)
    init_db(path)
    with sqlite3.connect(path) as conn:
        assert conn.execute("SELECT version, name FROM schema_migrations ORDER BY version").fetchall() == [
            (47, "reserved_for_128"), (48, "workspace_projects"),
        ]
        assert conn.execute("SELECT * FROM projects").fetchall() == []
        assert conn.execute("SELECT * FROM project_items").fetchall() == []
        assert conn.execute("SELECT * FROM library_sources").fetchall() == before_sources
        assert conn.execute("SELECT * FROM conversations").fetchall() == before_chats
        assert conn.execute("PRAGMA foreign_key_check").fetchall() == []


def test_v36_services_remain_visible_after_removal_migration(tmp_path):
    path = tmp_path / "tuantuan.db"
    init_db(path)
    with sqlite3.connect(path) as conn:
        conn.execute("INSERT INTO model_connections(id,name,effective_base_url,data_boundary) VALUES('saved','Saved','https://example.test/v1','saved')")
        conn.execute("ALTER TABLE model_connections DROP COLUMN deleted_at")
        conn.execute("UPDATE schema_migrations SET version=36, name='model_catalog_discovery'")
    init_db(path)
    with sqlite3.connect(path) as conn:
        assert conn.execute("SELECT id, enabled, deleted_at FROM model_connections").fetchall() == [("saved", 1, None)]
        assert conn.execute("PRAGMA foreign_key_check").fetchall() == []
    backup = tmp_path / ".upgrade-backups" / f"before-schema-v{DB_SCHEMA_VERSION}" / path.name
    with sqlite3.connect(backup) as conn:
        assert "deleted_at" not in columns(conn, "model_connections")
