"""Generate the frontend plan risk type from the backend Pydantic schema."""
from __future__ import annotations

import json
import sys
from pathlib import Path


REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPOSITORY_ROOT / "backend"))

from app.domain import AgentPlanStep  # noqa: E402


def main() -> None:
    risks = AgentPlanStep.model_json_schema()["properties"]["risk"]["enum"]
    values = json.dumps(risks, ensure_ascii=False, indent=2)
    output = REPOSITORY_ROOT / "frontend/src/features/chat/agent-plan-risk.generated.ts"
    output.write_text(
        "// Generated by backend/scripts/generate_agent_plan_risk.py; do not edit.\n"
        "\n"
        f"export const AGENT_PLAN_RISK_VALUES = {values} as const;\n"
        "\n"
        "export type AgentPlanRisk = (typeof AGENT_PLAN_RISK_VALUES)[number];\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"Generated {output.relative_to(REPOSITORY_ROOT)}")


if __name__ == "__main__":
    main()
